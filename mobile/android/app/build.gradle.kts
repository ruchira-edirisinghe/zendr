// Release signing comes from keystore.properties (git-ignored): storeFile, storePassword, keyAlias,
// keyPassword. Without it the release build is left unsigned.
val signing = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "dev.zendr.companion"
    compileSdk = 35

    defaultConfig {
        applicationId = "dev.zendr.companion"
        minSdk = 26
        targetSdk = 35
        versionCode = 203
        versionName = "0.2.3"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        // Each on-device test starts the app fresh, in its own process with its data cleared.
        testInstrumentationRunnerArguments["clearPackageData"] = "true"
    }

    signingConfigs {
        if (signing.getProperty("storeFile") != null) {
            create("release") {
                storeFile = file(signing.getProperty("storeFile"))
                storePassword = signing.getProperty("storePassword")
                keyAlias = signing.getProperty("keyAlias")
                keyPassword = signing.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // Not minified: the release runs exactly the code the on-device tests check (debug).
            isMinifyEnabled = false
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures { compose = true }
    testOptions { execution = "ANDROIDX_TEST_ORCHESTRATOR" }
}

